const custom = { zh: {}, "zh-HK": {} };
const loose = { zh: {}, "zh-HK": {} };
let pageNow = "";

export function pageFromPath(path) {
  const p = path || "/";
  if (p === "/") return "Home";
  if (p.startsWith("/venues")) return "Venues";
  if (p.startsWith("/quick")) return "Quick";
  if (p.startsWith("/private")) return "Private";
  if (p.startsWith("/me-time")) return "Me Time";
  if (p.startsWith("/how")) return "About";
  if (p.startsWith("/subscribe")) return "Plan";
  if (p.startsWith("/profile")) return "Profile";
  if (p.startsWith("/about")) return "About";
  if (p.startsWith("/register") || p.startsWith("/login")) return "Account";
  return "";
}

export function setWordingPage(page) {
  pageNow = page || "";
}

function nest(lang, bag) {
  const pages = {};
  const flat = {};
  if (bag && typeof bag === "object") {
    Object.entries(bag).forEach(([key, value]) => {
      if (typeof value === "string") flat[key] = value;
      else if (value && typeof value === "object") pages[key] = { ...value };
    });
  }
  loose[lang] = flat;
  return pages;
}

const savedValue = { zh: new Set(), "zh-HK": new Set() };
const byPage = { zh: new Map(), "zh-HK": new Map() };
const byAny = { zh: new Map(), "zh-HK": new Map() };

function normKey(text) {
  return String(text || "").replace(/\s+/g, " ").trim();
}

function indexBag(lang, page, bag) {
  Object.entries(bag || {}).forEach(([key, value]) => {
    if (typeof value !== "string" || !value.trim()) return;
    const id = normKey(key);
    byPage[lang].set(`${page}\0${id}`, value);
    if (!byAny[lang].has(id)) byAny[lang].set(id, value);
    else if (byAny[lang].get(id) !== value) byAny[lang].set(id, "\0");
    savedValue[lang].add(normKey(value));
  });
}

export function setWording(next) {
  ["zh", "zh-HK"].forEach((lang) => {
    custom[lang] = nest(lang, next?.[lang]);
    savedValue[lang] = new Set();
    byPage[lang] = new Map();
    byAny[lang] = new Map();
    Object.entries(custom[lang] || {}).forEach(([page, bag]) => indexBag(lang, page, bag));
    indexBag(lang, "", loose[lang]);
  });
}

function sameLine(a, b) {
  return normKey(a) === normKey(b);
}

export function wordingFor(lang, text, page = pageNow) {
  if (!lang || lang === "en") return "";
  const id = normKey(text);
  if (!id || !byPage[lang]) return "";
  const name = page || (typeof location !== "undefined" ? pageFromPath(location.pathname) : "");
  if (name) {
    const hit = byPage[lang].get(`${name}\0${id}`);
    if (hit) return hit;
  }
  const flat = byPage[lang].get(`\0${id}`);
  if (flat) return flat;
  const any = byAny[lang].get(id);
  return any && any !== "\0" ? any : "";
}

export function isSavedWording(text) {
  const id = normKey(text);
  if (!id) return false;
  return savedValue.zh.has(id) || savedValue["zh-HK"].has(id);
}

function exact(lang, text) {
  const own = wordingFor(lang, text);
  if (own) return own;
  const direct = PHRASE[text] || PHRASE[String(text).trim()];
  if (direct?.[lang]) return direct[lang];
  const fuzzy = Object.entries(PHRASE).find(([key]) => sameLine(key, text));
  return fuzzy?.[1]?.[lang] || "";
}

export function say(lang, text) {
  const raw = text == null ? "" : String(text);
  if (!raw || !lang || lang === "en") return raw;
  const whole = exact(lang, raw);
  if (whole) return whole;
  return raw;
}

export function named(item, lang, key = "name") {
  if (!item) return "";
  const bag = item.i18n?.[lang] || item.langs?.[lang] || {};
  return bag[key] || item[key] || "";
}
