export function resolveCopy(content, lang, key, legacy) {
  const stored = content?.copy?.locales?.[lang]?.[key];
  if (stored) return stored;
  if (lang === "en" && legacy) return legacy;
  const tr = translate(lang, key);
  if (tr !== key) return tr;
  return legacy || "";
}
